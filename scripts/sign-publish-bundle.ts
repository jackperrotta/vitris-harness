#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { artifactManifest } from "../src/knowledge/artifact.ts";
import { verifyReceipt, type EvidenceReceipt } from "../src/knowledge/evidence.ts";
import { KNOWLEDGE_RELEASE, LAUNCH_POLICY_ID } from "../src/knowledge/contracts.ts";
import { signPublishBundle, type PublishBundleBody } from "../src/knowledge/publish-attestation.ts";

const arg = (name: string) => { const index = process.argv.indexOf(name); return index < 0 ? undefined : process.argv[index + 1]; };
const site = resolve(arg("--site") || ".");
const output = arg("--out") && resolve(arg("--out")!);
const tenantId = arg("--tenant-id") || "";
const slug = arg("--slug") || "";
const project = arg("--project") || "";
const origin = arg("--origin");
const secret = process.env.VITRIS_PUBLISH_ATTESTATION_SECRET || "";
if (!output || !tenantId || !slug || !project || secret.length < 32) throw new Error("--out, --tenant-id, --slug, --project and VITRIS_PUBLISH_ATTESTATION_SECRET (32+ characters) are required");
const dist = join(site, "dist");
if (!existsSync(dist)) throw new Error("Build dist/ before signing a publish bundle");
const relOutput = relative(dist, output);
if (!relOutput.startsWith("..") && !isAbsolute(relOutput)) throw new Error("Attested bundle output must be outside dist/");
const siblingBin = join(dirname(fileURLToPath(import.meta.url)), "vitris-launch-preflight.js");
const sourceScript = join(dirname(fileURLToPath(import.meta.url)), "launch-preflight.ts");
const preflight = existsSync(siblingBin) ? [siblingBin] : ["--experimental-strip-types", sourceScript];
const checked = spawnSync(process.execPath, [...preflight, "--site", site, "--environment", "production", ...(origin ? ["--origin", origin] : [])], { encoding: "utf8", timeout: 180_000 });
if (checked.status !== 0) throw new Error(`Production preflight rejected this site: ${`${checked.stdout || ""}\n${checked.stderr || ""}`.slice(-1600)}`);
const report = JSON.parse(readFileSync(join(site, "agent/reviews/launch-preflight.json"), "utf8")) as { launchAllowed: boolean; buildHash: string };
const evidence = JSON.parse(readFileSync(join(site, "agent/reviews/launch-evidence.json"), "utf8")) as EvidenceReceipt;
const artifact = artifactManifest(dist);
if (!report.launchAllowed || !evidence.passed || !verifyReceipt(evidence).ok || evidence.policyHash !== LAUNCH_POLICY_ID || evidence.buildHash !== artifact.sha256 || report.buildHash !== artifact.sha256) throw new Error("Fresh preflight evidence does not bind the exact dist bytes");
const files = Object.fromEntries(artifact.files.map(file => [file.path, Buffer.from(readFileSync(join(dist, file.path))).toString("base64")]));
const issuedAt = Date.now();
const body: PublishBundleBody = { schemaVersion: 1, tenantId, slug, project, knowledgeRelease: KNOWLEDGE_RELEASE, issuedAt, expiresAt: issuedAt + 10 * 60_000, artifact, evidence, files };
const bundle = await signPublishBundle(body, secret);
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, JSON.stringify(bundle));
console.log(`Signed ${artifact.files.length} verified files for ${slug}/${project}; expires ${new Date(bundle.expiresAt).toISOString()}`);
